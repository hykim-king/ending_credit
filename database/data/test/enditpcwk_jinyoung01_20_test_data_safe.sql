-- Ending Credit - jinyoung01~20 공용 DB 테스트 데이터 안전 등록
--
-- 실행 방법
-- - Oracle SQL Developer에서는 반드시 Run Script(F5)로 실행한다.
-- - 기존 일반 회원과 기존 데이터는 삭제하지 않는다.
-- - jinyoung01~20 이메일 또는 닉네임이 이미 있으면 아무것도 등록하지 않는다.
-- - 모든 DML과 건수 검증이 성공해야 마지막 COMMIT이 실행된다.
-- - 오류가 발생하면 WHENEVER SQLERROR에 의해 전체 ROLLBACK 후 종료된다.
-- - 회원 비밀번호는 화면 데이터 테스트용 더미 값이므로 로그인할 수 없다.
-- =====================================================================

SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK


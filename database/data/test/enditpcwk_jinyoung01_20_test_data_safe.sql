CANDIDATE_RAW AS (
    SELECT M.MEMBER_ID,
           P.EMAIL,
           P.TARGET_CNT,
           P.PREF_ROLE,
           MC.CONTENT_ID,
           MC.RATING_SCORE,
           MC.RATED_DT,
           CC.PERSON_ID,
           CC.ROLE,
           CC.DISPLAY_ORDER,

           -- 같은 인물이 여러 평가 영화에 등장하는 경우 1명으로 중복 제거
           ROW_NUMBER() OVER (
               PARTITION BY M.MEMBER_ID, CC.PERSON_ID
               ORDER BY
                   MC.RATING_SCORE DESC,
                   CASE CC.ROLE
                       WHEN 'ACTOR'    THEN 1
                       WHEN 'DIRECTOR' THEN 2
                       ELSE 3
                   END,
                   CC.DISPLAY_ORDER ASC,
                   MC.RATED_DT DESC,
                   MC.CONTENT_ID ASC
           ) AS PERSON_DUP_RN
      FROM PROFILE P
      JOIN MEMBER M
        ON M.EMAIL = P.EMAIL
      JOIN MEMBER_CONTENT MC
        ON MC.MEMBER_ID = M.MEMBER_ID
       AND MC.RATING_SCORE IS NOT NULL
      JOIN CONTENT_CREDIT CC
        ON CC.CONTENT_ID = MC.CONTENT_ID
     WHERE CC.ROLE IN ('ACTOR', 'DIRECTOR')
       AND (
             P.PREF_ROLE = 'ALL'
          OR P.PREF_ROLE = CC.ROLE
       )
),
CANDIDATE AS (
    SELECT MEMBER_ID,
           EMAIL,
           TARGET_CNT,
           PREF_ROLE,
           CONTENT_ID,
           RATING_SCORE,
           RATED_DT,
           PERSON_ID,
           ROLE,
           DISPLAY_ORDER
      FROM CANDIDATE_RAW
     WHERE PERSON_DUP_RN = 1
),
RANKED AS (
    SELECT C.*,
           ROW_NUMBER() OVER (
               PARTITION BY C.MEMBER_ID
               ORDER BY
                   C.RATING_SCORE DESC,
                   CASE C.ROLE
                       WHEN 'ACTOR'    THEN 1
                       WHEN 'DIRECTOR' THEN 2
                       ELSE 3
                   END,
                   C.DISPLAY_ORDER ASC,
                   C.RATED_DT DESC,
                   C.PERSON_ID ASC
           ) AS RN
      FROM CANDIDATE C
)
SELECT MEMBER_ID,
       PERSON_ID,

       -- 평가 이후 좋아요를 누른 것처럼 처리
       LEAST(
           SYSDATE,
           NVL(RATED_DT, SYSDATE) + 1
       ) AS CREATED_DT
  FROM RANKED
 WHERE RN <= TARGET_CNT;


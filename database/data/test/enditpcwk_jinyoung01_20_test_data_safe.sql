-- 0. 사전 충돌 검사
-- 이메일 또는 닉네임이 하나라도 이미 존재하면 기존 데이터를 건드리지 않고 중단한다.
-- ---------------------------------------------------------------------
DECLARE
    V_COLLISION_COUNT NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO V_COLLISION_COUNT
      FROM MEMBER
     WHERE REGEXP_LIKE(
               LOWER(EMAIL),
               '^jinyoung(0[1-9]|1[0-9]|20)@endit\.com$'
           )
        OR REGEXP_LIKE(
               LOWER(NICKNAME),
               '^jinyoung(0[1-9]|1[0-9]|20)$'
           );

    IF V_COLLISION_COUNT > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20001,
            'jinyoung01~20 이메일 또는 닉네임이 이미 존재합니다. 등록을 중단합니다.'
        );
    END IF;
END;

SELECT M.NICKNAME,
       (
           SELECT COUNT(*)
             FROM MEMBER_CONTENT MC
            WHERE MC.MEMBER_ID = M.MEMBER_ID
       ) AS MEMBER_CONTENT_CNT,
       (
           SELECT COUNT(*)
             FROM COLLECTION C
            WHERE C.MEMBER_ID = M.MEMBER_ID
       ) AS COLLECTION_CNT,
       (
           SELECT COUNT(*)
             FROM COLLECTION_LIKE CL
            WHERE CL.MEMBER_ID = M.MEMBER_ID
       ) AS COLLECTION_LIKE_CNT,
       (
           SELECT COUNT(*)
             FROM PERSON_LIKE PL
            WHERE PL.MEMBER_ID = M.MEMBER_ID
       ) AS PERSON_LIKE_CNT
  FROM MEMBER M
 WHERE REGEXP_LIKE(
           LOWER(M.EMAIL),
           '^jinyoung(0[1-9]|1[0-9]|20)@endit\.com$'
       )
 ORDER BY M.NICKNAME;

SELECT M.NICKNAME,
       P.PERSON_ID,
       COALESCE(P.NAME_KO, P.NAME_ORG) AS PERSON_NAME,
       PL.CREATED_DT
  FROM PERSON_LIKE PL
  JOIN MEMBER M
    ON M.MEMBER_ID = PL.MEMBER_ID
  JOIN PERSON P
    ON P.PERSON_ID = PL.PERSON_ID
 WHERE REGEXP_LIKE(
           LOWER(M.EMAIL),
           '^jinyoung(0[1-9]|1[0-9]|20)@endit\.com$'
       )
 ORDER BY M.NICKNAME,
          PL.CREATED_DT DESC,
          P.PERSON_ID;

